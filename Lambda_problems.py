# # Write a lambda function to square a number

sqfn = lambda x:x**2

print(sqfn(9))

# Write a lambda to add two numbers

addfn = lambda a,b:a+b

print(addfn(2,9))

# Use lambda to check if a number is even or odd

chnum = lambda x: "even" if x%2==0 else "odd"

print(chnum(231))

# Write a lambda to find maximum of two numbers

maxnum = lambda a,b: a if a>b else b

print(maxnum(45,67))

